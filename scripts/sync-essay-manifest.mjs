// The archive is the source of truth for random picks, including fetch failures.
// Run normally to regenerate, or with --check in pre-publish verification.
import { readFile, writeFile, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const archive = await readFile(new URL('thoughts/index.html', root), 'utf8');
const list = archive.match(/<ul\b[^>]*id="article-list"[^>]*>([\s\S]*?)<\/ul>/)?.[1];
if (!list) throw new Error('Missing #article-list in the Thoughts archive.');
const essays = [...list.matchAll(/<a\b[^>]*href="([a-z0-9-]+\.html)"/g)].map(match => match[1]);
if (!essays.length || new Set(essays).size !== essays.length) throw new Error('Essay archive is empty or has duplicate slugs.');
await Promise.all(essays.map(slug => access(new URL(`thoughts/${slug}`, root))));
const source = '// Generated by scripts/sync-essay-manifest.mjs from thoughts/index.html. Do not edit by hand.\n' +
    `window.WILLIS_ESSAYS = Object.freeze(${JSON.stringify(essays, null, 4)});\n`;
const target = new URL('thoughts/essay-manifest.js', root);
if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8').catch(() => '') !== source) {
        throw new Error('Essay manifest is stale. Run node scripts/sync-essay-manifest.mjs before publishing.');
    }
    console.log(`Essay manifest matches all ${essays.length} archived essays.`);
} else {
    await writeFile(target, source);
    console.log(`Generated ${fileURLToPath(target)} (${essays.length} essays).`);
}
