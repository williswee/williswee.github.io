// The archive owns order and random picks; each essay owns its title and text.
// Run normally to regenerate, or with --check in pre-publish verification.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const archive = await readFile(new URL('thoughts/index.html', root), 'utf8');
const list = archive.match(/<ul\b[^>]*id="article-list"[^>]*>([\s\S]*?)<\/ul>/)?.[1];
if (!list) throw new Error('Missing #article-list in the Thoughts archive.');
const essays = [...list.matchAll(/<a\b[^>]*href="([a-z0-9-]+\.html)"/g)].map(match => match[1]);
if (!essays.length || new Set(essays).size !== essays.length) throw new Error('Essay archive is empty or has duplicate slugs.');

function plainText(html) {
    const entities = {
        amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ',
        lsquo: '‘', rsquo: '’', ldquo: '“', rdquo: '”', ndash: '–', mdash: '—',
        hellip: '…', rarr: '→', sup1: '¹'
    };
    return html.replace(/<!--[\s\S]*?-->/g, ' ')
        .replace(/<(script|style)\b[^>]*>[\s\S]*?<\/\1>/gi, ' ')
        .replace(/<[^>]+>/g, ' ')
        .replace(/&(#x[\da-f]+|#\d+|[a-z][\da-z]+);/gi, (entity, name) => {
            if (!name.startsWith('#')) return entities[name.toLowerCase()] ?? entity;
            const point = name[1].toLowerCase() === 'x' ? parseInt(name.slice(2), 16) : Number(name.slice(1));
            return point > 0 && point <= 0x10ffff ? String.fromCodePoint(point) : '�';
        }).replace(/\s+/g, ' ').trim();
}

const details = await Promise.all(essays.map(async slug => {
    const html = await readFile(new URL(`thoughts/${slug}`, root), 'utf8');
    const article = html.match(/<article\b[^>]*>([\s\S]*?)<\/article>/)?.[1];
    const title = article?.match(/<h1\b[^>]*>([\s\S]*?)<\/h1>/)?.[1];
    const date = article?.match(/<p\b[^>]*class="article-date"[^>]*>([\s\S]*?)<\/p>/)?.[1];
    if (!article || !title || !date) throw new Error(`Missing essay title, date, or article in ${slug}.`);
    // Include captions and footnotes, but not publication metadata or HTML attrs.
    // This is a reading estimate; watching embedded demos is additional time.
    const words = plainText(article.replace(/<p\b[^>]*class="article-(?:date|author)"[^>]*>[\s\S]*?<\/p>/g, ' '))
        .match(/[\p{L}\p{N}]+(?:['’][\p{L}\p{N}]+)*/gu) ?? [];
    return { slug, title: plainText(title), date: plainText(date), minutes: Math.max(1, Math.ceil(words.length / 220)) };
}));
const source = '// Generated by scripts/sync-essay-manifest.mjs from thoughts/index.html. Do not edit by hand.\n' +
    `window.WILLIS_ESSAYS = Object.freeze(${JSON.stringify(essays, null, 4)});\n` +
    `window.WILLIS_ESSAY_DETAILS = Object.freeze(${JSON.stringify(details, null, 4)});\n`;
const target = new URL('thoughts/essay-manifest.js', root);
if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8').catch(() => '') !== source) {
        throw new Error('Essay manifest is stale. Run node scripts/sync-essay-manifest.mjs before publishing.');
    }
    console.log(`Essay manifest matches all ${essays.length} archived essays.`);
} else {
    await writeFile(target, source);
    console.log(`Generated ${fileURLToPath(target)} (${essays.length} essays).`);
}
